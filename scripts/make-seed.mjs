// Builds data/seed.sql (gitignored) from the exported sheet and the filled-in pinyin/meaning.
//
//   node scripts/make-seed.mjs [data/sheet.csv] [data/fill.tsv]
//
// sheet.csv : the Google Sheet exported as CSV (columns: 章, 汉语, ピンイン, 意味, 量詞か？, 品詞メモ)
// fill.tsv  : hanzi <TAB> pinyin <TAB> meaning [<TAB> 1 = needs check]
//
// Run the generated SQL in the Supabase SQL Editor after logging in once, so the
// user exists in auth.users. Words that already exist are left untouched.
import { readFileSync, writeFileSync } from "node:fs";

const sheetPath = process.argv[2] ?? "data/sheet.csv";
const fillPath = process.argv[3] ?? "data/fill.tsv";

// Cells that hold two words because a line break is missing in the sheet.
const SPLITS = { 睡觉说服: ["睡觉", "说服"] };

const fill = new Map();
for (const line of readFileSync(fillPath, "utf8").split(/\r?\n/)) {
  if (!line.trim()) continue;
  const [hanzi, pinyin, meaning, check] = line.split("\t");
  fill.set(hanzi, { pinyin, meaning, check: check === "1" });
}

const rows = readFileSync(sheetPath, "utf8").split(/\r?\n/).slice(1);
const seen = new Set();
const words = [];
const missing = [];
let chapter = null;
for (const row of rows) {
  const [chapterCell, hanziCell, , , measure, posNote] = row.split(",");
  if (chapterCell) chapter = Number(chapterCell);
  if (!hanziCell) continue;
  for (const hanzi of SPLITS[hanziCell] ?? [hanziCell]) {
    const key = `${chapter}:${hanzi}`;
    if (seen.has(key)) continue; // same word twice in one chapter
    seen.add(key);
    const f = fill.get(hanzi);
    if (!f) {
      missing.push(hanzi);
      continue;
    }
    words.push({
      chapter,
      hanzi,
      ...f,
      isMeasureWord: measure?.trim().toUpperCase() === "TRUE",
      posNote: posNote?.trim() || null,
      position: words.length + 1,
    });
  }
}

if (missing.length > 0) {
  console.error(`No pinyin/meaning for: ${missing.join(" ")}`);
  process.exit(1);
}

const q = (s) => `'${s.replaceAll("'", "''")}'`;
const values = words
  .map(
    (w) =>
      `  (${w.chapter}, ${q(w.hanzi)}, ${q(w.pinyin)}, ${q(w.meaning)}, ${w.isMeasureWord}, ${
        w.posNote ? q(w.posNote) : "null::text"
      }, ${w.check}, ${w.position})`,
  )
  .join(",\n");

const sql = `-- Generated by scripts/make-seed.mjs. Do not commit.
insert into public.words
  (user_id, chapter, hanzi, pinyin, meaning, is_measure_word, pos_note, needs_check, position)
select u.id, v.*
from (select id from auth.users order by created_at limit 1) u,
(values
${values}
) as v(chapter, hanzi, pinyin, meaning, is_measure_word, pos_note, needs_check, position)
on conflict (user_id, chapter, hanzi) do nothing;
`;

writeFileSync("data/seed.sql", sql);
console.log(`Wrote data/seed.sql (${words.length} words, ${words.filter((w) => w.check).length} flagged for check)`);
